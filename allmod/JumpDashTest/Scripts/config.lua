local config = {
    -- Мастер-выключатель (false = полное возвращение к ванили)
    Enabled = true,

    -- Подробный лог в консоль UE4SS (для теста; включить на лету: !jd debug)
    Debug = false,

    -- === 1) Air Dash Boots (пассивка AirDash) ===
    -- Множитель ДИСТАНЦИИ рывка. Ваниль = 400 см (4 м) за 0.5 с.
    -- 5.0 -> 20 м, 10.0 -> 40 м. Скорость растёт пропорционально,
    -- рывок остаётся резким «выстрелом» (кривая рывка не меняется).
    AirDashDistanceMult = 5.0,
    -- Множитель ВРЕМЕНИ рывка. 1.0 = ваниль (0.5 с). 0.5 = вдвое резче.
    -- Выше 1.25 не ставить — срежется внутренним Const_MaxAirborneTime (0.4 с).
    AirDashTimeMult = 1.0,

    -- === 2) Jump Boots (пассивка JumpCount_Increase) ===
    -- Сколько ДОПОЛНИТЕЛЬНЫХ прыжков даёт пассивка (ваниль: 1/2/3).
    -- Итоговое число прыжков = 1 (обычный) + это значение.
    ExtraJumpCount = 5,

    -- === 3) Anti-Gravity Belt (пассивка JumpPower_Increase) ===
    -- Множитель СИЛЫ прыжка, пока пояс надет. 1.0 = ваниль (пояс даёт +25%).
    -- Высота растёт примерно как квадрат: x2.0 силы = ~x4 высоты.
    JumpPowerMult = 2.0,
}

return config
